// 为什么单独拆出来（步骤十「D. fallback 也遵守人物和时代边界」）：
//   兜底回复过去内嵌在 index.js 里，而 index.js 依赖 wx-server-sdk（云环境），
//   测试无法 require。抽成独立模块后，可以本地断言：
//     · 三个人物 × 每个时期都有文案（不会掉到"回神"通用句）；
//     · 每个文案只提本人物、本时期的事（不串线、不预知未来）；
//     · 非法 npc / 未知时期安全回退，不抛错。
//   index.js 仍按原样调用，行为不变。

// 内容安全拦截时的兜底（人设内，不冷场、不说教）
