function getAnchorInfo(lineId, anchorId) {
  const lib = LINE_INFO[lineId];
  if (!lib) return null;
  return lib[anchorId] || null;
}

/**
 * 从学生这句话里挑出一个"说中的关键词"，用来生成
 * 「因为你说出了「杜审言」」这类反馈。
 *
 * 规则：取所有命中的关键词里**最长的**那一个。
 * 因为短词往往是长词的子串——输入"杜甫的祖父应该是杜审言吧"时，
 * 若返回先命中的"祖父"就浪费了一条更精确的信息；命中"会当凌绝顶"时
 * 也不该退回更短的"望岳"。
 *
 * 不修改原始 keywords 数组（只做读取比较）；
 * 一个都没命中时返回空串，卡片会退回中性文案，不编造。
 */
function pickQuote(text, info) {
  const t = text || '';
  const kws = (info && info.keywords) || [];
  let best = '';
  for (let i = 0; i < kws.length; i++) {
    const kw = kws[i];
    if (kw && t.indexOf(kw) >= 0 && kw.length > best.length) best = kw;
  }
  return best;
}

