// utils/stories/anchor-info.js —— 知识锚点的「展示内容表」（知识落印三步用）
//
// 与 line-*.js 的 ANCHORS（id → 名称）分工不同：
//   ANCHORS      只存名字，供进度统计 / 集卡展示，是「钩子」；
//   ANCHOR_INFO  存这一枚印记的「一句话知识 / 完整史料 / 关联 / 关键词」，
//                是「学习反馈」——知识卡要回答的三件事全靠它：
//                  ① 我获得了什么 → line.anchors[anchorId]
//                  ② 为什么获得   → kind + keywords 本地比对（不需要云函数配合）
//                  ③ 我学到了什么 → know（一句话） / detail（主动展开）
//
// 未收录的锚点走 FALLBACK：卡片仍然照常出现，只是内容提示「整理中」，
// 不会因为某条线还没写文案就整块功能失效。
//
// 新增锚点文案的写法：
//   know   一句话，40–60 字，必须能独立看懂（这是默认只展示的那一句）
//   detail 完整史料，150–250 字，可含出处；给"想深挖"的学生看
//   links  关联条目，3 条左右，指向同一时期的其它知识点
//   keywords 学生可能说出的关键词，用于生成"因为你说出了「杜审言」"
//   poem   （可选）该锚点挂的诗，见下方 poem 字段说明；没有就不写，卡片自动退回 know

// ============ poem 字段说明（只给需要"读原诗"的锚点加）============
//   poem: {
//     title: '望岳',                 // 诗题，不带书名号（模板里自动加《》）
//     author: '杜甫',
//     displayMode: 'full',           // 'full' 全诗 | 'excerpt' 节选（长诗/只引片段用）
//     lines: [                       // 逐句结构化，不要从 detail 里正则抠诗句
//       { text: '岱宗夫如何？齐鲁青未了。', highlight: false },
//       { text: '会当凌绝顶，一览众山小。', highlight: true }
//     ],
//     insight: '一句话解读，放在诗文下方'
//   }
//   · highlight 为 true 的句子：轻量卡只挑它们展示，完整史料面板用朱砂色强调
//   · displayMode 目前只影响完整史料面板的样式（'excerpt' 会在诗名旁标"节选"）
//   · 诗名/作者/句数都不写死在模板里，换任何诗都不用改代码
//
// ============ 排版约定（三条，加新诗时照做）============
//   ① 一行装多少字，取决于字体（音/歌行）：
//        律诗、绝句 → 一行 = 一联（两个分句），五律 12 字、七律 16 字；
//        歌行、杂言 → 一行 = 一个分句（律诗的整齐在杂言里不成立，强行合并会读不通）
//   ② 每行（含标点）**不要超过 16 字**。两个约束倒推出来的：
//        · 轻量卡的诗句行是 nowrap + 省略号，卡片内宽 564rpx / 27rpx 字 ≈ 20 字封顶；
//        · 完整史料面板的诗句区更窄（≈16 字），超出会折行。取 16 是两者的交集。
//      长句宁可拆行，也不要让它被省略号截掉半句。
//   ③ highlight 选 **know 已经引过的那一联**（或那一句）。
//      轻量卡有 poem 时会用摘句**替代** know，这样选能保证卡片上的信息一点不丢；
//      同时「一句话知识」和诗歌区强调的也是同一句，前后不打架。
//      a2 标尾联、a16 标颔联，都是各自 know 引过的那一联——不是随手挑的。
//      歌行没有"联"，标 know 引到的那一个完整句即可（允许标 2 行，如 a8）。
//
//   · 挂了 poem 之后，detail 里**不要再出现完整的诗句原句**（赏析写进 insight），
//     否则同一句诗会在面板里出现两遍。作为论据的**词组级**引用可以留
//     （如 a4 的「家书抵万金」、a16 的「百年多病」），那不是重复排版。

